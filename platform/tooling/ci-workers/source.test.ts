import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { command } from './core.ts';
import { lockData } from './source.ts';

test('preparation accepts lockfiles generated by the pinned Bun without lifecycle scripts', async t => {
  await mkdir('.ci-local-artifacts', { recursive: true });
  const dir = await mkdtemp(path.join(process.cwd(), '.ci-local-artifacts/worker-generated-lock-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  await mkdir(path.join(dir, 'local'));
  await writeFile(path.join(dir, 'package.json'), JSON.stringify({ name: 'generated-lock', dependencies: { local: 'file:local' } }));
  await writeFile(path.join(dir, 'local/package.json'), JSON.stringify({ name: 'local', version: '1.0.0', scripts: { postinstall: 'exit 1' } }));
  const pinned = JSON.parse(await readFile('package.json', 'utf8')).packageManager.replace(/^bun@/, '');
  assert.equal(await command('bun', ['--version']), pinned);
  await command('bun', ['install', '--lockfile-only', '--ignore-scripts', '--offline'], { cwd: dir });
  const generated = await readFile(path.join(dir, 'bun.lock'), 'utf8');
  // Bun 1.4.4+ flags the declared postinstall; preparation still never runs it.
  assert.deepEqual(lockData(generated).packages.local, ['local@file:local', { hasInstallScript: true }]);
});

function nativeLock(metadata: Record<string, unknown>): string {
  return JSON.stringify({ lockfileVersion: 1, workspaces: {}, packages: {
    '@next/swc-linux-x64-gnu': ['@next/swc-linux-x64-gnu@16.4.4', '', metadata, 'sha512-fixture'],
  } });
}

test('preparation accepts libc selectors in native package metadata', () => {
  for (const libc of ['glibc', 'musl', ['glibc', 'musl']]) {
    const metadata = { os: 'linux', cpu: 'x64', libc };
    assert.deepEqual(lockData(nativeLock(metadata)).packages['@next/swc-linux-x64-gnu'][2], metadata);
  }
});

test('preparation rejects malformed libc selectors and unknown package metadata', () => {
  for (const libc of [null, 42, {}, ['glibc', 42]]) {
    assert.throws(() => lockData(nativeLock({ libc })), /Unsupported package metadata value/);
  }
  assert.throws(() => lockData(nativeLock({ unknown: 'value' })), /Unsupported lock package metadata/);
});
